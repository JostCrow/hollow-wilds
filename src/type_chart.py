def get_type_effectiveness(move_type: str, defender_types: list[str]) -> float:
    """
    Calculate the type effectiveness multiplier for a move against a defender.
    
    Args:
        move_type: The type of the attacking move
        defender_types: List of types of the defending creature (can have 1 or 2 types)
    
    Returns:
        float: The effectiveness multiplier (0.0, 0.25, 0.5, 1.0, 2.0, or 4.0)
    """
    if move_type not in TYPE_CHART:
        return 1.0  # Unknown type defaults to neutral
    
    multiplier = 1.0
    for defender_type in defender_types:
        if defender_type in TYPE_CHART[move_type]:
            multiplier *= TYPE_CHART[move_type][defender_type]
        else:
            multiplier *= 1.0  # Unknown defender type defaults to neutral
    
    return multiplier


def get_effectiveness_message(effectiveness: float) -> str:
    """
    Get a message describing the type effectiveness.
    
    Args:
        effectiveness: The effectiveness multiplier
    
    Returns:
        str: A message like "It's super effective!" or "It's not very effective..."
    """
    if effectiveness >= 2.0:
        return "It's super effective!"
    elif effectiveness == 0.0:
        return "It doesn't affect the target..."
    elif effectiveness <= 0.5:
        return "It's not very effective..."
    else:
        return ""